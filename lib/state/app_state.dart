import 'package:flutter/material.dart';
import 'package:shared_preferences/shared_preferences.dart';

import '../data/demo_content.dart';
import '../models/activity.dart';
import '../models/demo_thread.dart';

/// Local-only application state.
///
/// Favorites and the theme preference survive restarts. Demo conversations are
/// intentionally in-memory: the app never sends, stores remotely, or claims to
/// deliver a message.
class AppState extends ChangeNotifier {
  AppState._(
    this._preferences,
    this._favorites,
    this._themeMode,
    this._threads,
  );

  static const _favoritesKey = 'busypro.favorites';
  static const _themeKey = 'busypro.themeMode';

  final SharedPreferences _preferences;
  final Set<String> _favorites;
  ThemeMode _themeMode;
  final List<DemoThread> _threads;

  static Future<AppState> load() async {
    final preferences = await SharedPreferences.getInstance();
    final savedTheme = preferences.getString(_themeKey);
    final themeMode = ThemeMode.values.firstWhere(
      (mode) => mode.name == savedTheme,
      orElse: () => ThemeMode.system,
    );

    return AppState._(
      preferences,
      (preferences.getStringList(_favoritesKey) ?? <String>[]).toSet(),
      themeMode,
      seedDemoThreads(),
    );
  }

  ThemeMode get themeMode => _themeMode;

  Set<String> get favoriteIds => Set<String>.unmodifiable(_favorites);

  int get favoriteCount => _favorites.length;

  List<ActivityDefinition> get favoriteActivities => activities
      .where((activity) => _favorites.contains(activity.id))
      .toList(growable: false);

  bool isFavorite(String activityId) => _favorites.contains(activityId);

  List<DemoThread> threadsFor(DemoChannel channel) =>
      List<DemoThread>.unmodifiable(
        _threads.where((thread) => thread.channel == channel),
      );

  DemoThread? threadById(String id) {
    for (final thread in _threads) {
      if (thread.id == id) return thread;
    }
    return null;
  }

  Future<void> toggleFavorite(String activityId) async {
    if (!_favorites.remove(activityId)) {
      _favorites.add(activityId);
    }
    notifyListeners();
    await _preferences.setStringList(
      _favoritesKey,
      _favorites.toList()..sort(),
    );
  }

  Future<void> setThemeMode(ThemeMode mode) async {
    if (_themeMode == mode) return;
    _themeMode = mode;
    notifyListeners();
    await _preferences.setString(_themeKey, mode.name);
  }

  /// Adds the user's line to a demo thread. It is never delivered as SMS or
  /// Instagram content; the chat screen may send the transcript to Hugging
  /// Face for an AI reply.
  void sendMessage(String threadId, String text) {
    final trimmed = text.trim();
    if (trimmed.isEmpty) return;
    final thread = threadById(threadId);
    if (thread == null) return;
    thread.messages.add(
      DemoMessage(text: trimmed, isMine: true, sentAt: DateTime.now()),
    );
    notifyListeners();
  }

  /// Adds an incoming demo reply and records whether it was generated by the
  /// AI or by the offline sample engine.
  void addReply(
    String threadId,
    String text, {
    required DemoMessageSource source,
  }) {
    final trimmed = text.trim();
    if (trimmed.isEmpty) return;
    final thread = threadById(threadId);
    if (thread == null) return;
    thread.messages.add(
      DemoMessage(
        text: trimmed,
        isMine: false,
        sentAt: DateTime.now(),
        source: source,
      ),
    );
    notifyListeners();
  }

  /// Restores the sample conversations and clears favorites.
  /// The chosen theme is a user preference, not demo data, so it is retained.
  Future<void> resetDemoData() async {
    _favorites.clear();
    _threads
      ..clear()
      ..addAll(seedDemoThreads());
    notifyListeners();
    await _preferences.remove(_favoritesKey);
  }
}
